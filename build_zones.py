def extract_areas(code, snapshots):
    """Distinct place fragments from the feeder's addresses (auto gazetteer)."""
    frags = []
    seen = set()
    for r in snapshots:
        for it in r.get("items", []):
            addr = it.get("address", "")
            if not addr.startswith(code):
                continue
            body = addr[len(code):]
            for part in re.split(r"[-،,؛]", body):
                part = part.strip()
                if 3 <= len(part) <= 30 and part not in seen:
                    seen.add(part)
                    frags.append(part)
    return frags[:8]


def build(out_path=DEFAULT_OUT):
    hist = status_model.load_history(HISTORY)
    dates = [jalali.today_str(), jalali.date_offset_str(1)]
    snaps = [r for r in hist if r.get("date") in dates]
    zones = []
    for code in sorted(CENTROIDS, key=lambda c: (len(c), c)):
        lat, lng, r, label = CENTROIDS[code]
        if code in CORRIDORS:
            p1, p2, w = CORRIDORS[code]
            poly = band(p1, p2, w * 0.8)
            shape = "corridor"
        else:
            poly = hexagon(lat, lng, r)
            shape = "hex"
        zones.append({
            "feeder": code,
            "area": AREA_OF[code],
            "name": f"فیدر {code} — {label}",
            "areas": extract_areas(code, snaps),
            "polygon": poly,
            "shape": shape,
            "approximate": True,
        })
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(zones, f, ensure_ascii=False, indent=1)
    return zones


