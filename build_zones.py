def hexagon(lat, lng, r, n=6):
    pts = []
    for i in range(n):
        ang = 2 * math.pi * i / n
        pts.append([lat + r * math.sin(ang), lng + r * math.cos(ang)])
    pts.append(pts[0])  # close ring
    return pts


def band(p1, p2, w):
    """Rectangular corridor along segment p1->p2 with half-width w (deg)."""
    lat1, lng1 = p1
    lat2, lng2 = p2
    dx, dy = lat2 - lat1, lng2 - lng1
    d = math.hypot(dx, dy) or 1e-9
    ux, uy = dx / d, dy / d          # unit along
    nx, ny = -uy, ux                 # unit normal
    return [
        [lat1 + nx * w, lng1 + ny * w],
        [lat1 - nx * w, lng1 - ny * w],
        [lat2 - nx * w, lng2 - ny * w],
        [lat2 + nx * w, lng2 + ny * w],
        [lat1 + nx * w, lng1 + ny * w],
    ]


